// Generates `<functions>/migrations/_generated.ts` from the numbered migration
// files next to it, and `<functions>/seeds/_generated.ts` from the seed files.
// Both are committed, like Convex's own `_generated/`.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import type { Project } from './project.ts';

export const GENERATED_FILE = '_generated.ts';

/** `0001_rename_body.ts`: a number, an underscore, a name. */
export const MIGRATION_FILE = /^(\d+)_([a-z0-9_]+)\.(ts|js)$/;

export interface MigrationFile {
  /** The number prefix, e.g. 1 for `0001_rename_body.ts`. */
  number: number;
  /** The module name without extension, e.g. `0001_rename_body`. */
  module: string;
  file: string;
}

export class MigrationFileError extends Error {}

/** The numbered migration files, in the order they run. */
export function listMigrations(migrationsDir: string): MigrationFile[] {
  if (!existsSync(migrationsDir)) return [];
  const files: MigrationFile[] = [];
  for (const file of readdirSync(migrationsDir).sort()) {
    if (file.startsWith('_') || file.startsWith('.') || !/\.(ts|js)$/.test(file)) continue;
    if (/\.(test|spec|d)\.(ts|js)$/.test(file)) continue;
    const match = MIGRATION_FILE.exec(file);
    if (!match) {
      throw new MigrationFileError(
        `${file}: migration files are named like 0001_rename_body.ts (a number, an underscore, lowercase letters, digits and underscores).`,
      );
    }
    files.push({ number: Number(match[1]), module: file.replace(/\.(ts|js)$/, ''), file });
  }
  files.sort((a, b) => a.number - b.number);
  for (let i = 1; i < files.length; i++) {
    if (files[i]!.number === files[i - 1]!.number) {
      throw new MigrationFileError(`${files[i - 1]!.file} and ${files[i]!.file} have the same number; each migration needs its own.`);
    }
  }
  return files;
}

export function renderGenerated(migrations: MigrationFile[], packageName = '@dev-marzahn/convex-release'): string {
  const list = migrations.length === 0 ? '[]' : `[\n${migrations.map((m) => `  internal.migrations[${JSON.stringify(m.module)}].default,`).join('\n')}\n]`;
  return `/* eslint-disable */
/**
 * Generated by convex-release from the numbered files in this folder.
 *
 * Don't edit it: \`convex-release new\` and \`convex-release codegen\` rewrite it.
 * @module
 */

import { createRelease } from "${packageName}";
import { components, internal } from "../_generated/api";
import type { DataModel } from "../_generated/dataModel";

const release = createRelease<DataModel>(components.migrations);

/**
 * Defines a data migration. In a numbered file in this folder:
 *
 * \`\`\`ts
 * export default defineMigration({
 *   table: "messages",
 *   migrateOne: (ctx, doc) => { ... },
 * });
 * \`\`\`
 */
export const defineMigration = release.defineMigration;

/** Run by the release image and \`convex-release migrate\`, oldest first. */
export const { start, status } = release.upgrade(${list});
`;
}

/** A seed file's name: letters, digits, `_` and `-`, so it's a valid Convex module. */
export const SEED_FILE = /^[A-Za-z0-9_-]+\.(ts|js)$/;

/**
 * The seed files' module names, in the order they run: by number prefix if
 * they have one (`2_users` before `10_messages`), then by name.
 */
export function listSeeds(seedsDir: string): string[] {
  if (!existsSync(seedsDir)) return [];
  const modules: string[] = [];
  for (const file of readdirSync(seedsDir)) {
    if (file.startsWith('_') || file.startsWith('.') || !/\.(ts|js)$/.test(file)) continue;
    if (/\.(test|spec|d)\.(ts|js)$/.test(file)) continue;
    if (!SEED_FILE.test(file)) throw new MigrationFileError(`${file}: seed file names use letters, digits, underscores and dashes, like 01_users.ts.`);
    modules.push(file.replace(/\.(ts|js)$/, ''));
  }
  const number = (module: string) => Number(/^(\d+)/.exec(module)?.[1] ?? Infinity);
  return modules.sort((a, b) => number(a) - number(b) || (a < b ? -1 : a > b ? 1 : 0));
}

export function renderSeedsGenerated(seeds: string[], packageName = '@dev-marzahn/convex-release'): string {
  const list = seeds.length === 0 ? '[]' : `[\n${seeds.map((s) => `  internal.seeds[${JSON.stringify(s)}].default,`).join('\n')}\n]`;
  return `/* eslint-disable */
/**
 * Generated by convex-release from the files in this folder.
 *
 * Don't edit it: \`convex-release new\`, \`codegen\`, \`dev\` and \`deploy\` rewrite it.
 * @module
 */

import { createSeeds } from "${packageName}/seed";
import { internal } from "../_generated/api";
import type { DataModel } from "../_generated/dataModel";
import schema from "../schema";

const seeds = createSeeds<DataModel>(schema);

/**
 * Defines a seed. In a file in this folder:
 *
 * \`\`\`ts
 * export default defineSeed("users", {
 *   count: 50,
 *   fields: { name: ({ faker }) => faker.person.fullName() },
 * });
 * \`\`\`
 */
export const defineSeed = seeds.defineSeed;

/** Run by \`convex-release seed\`, \`dev\` and the release images, in this order. */
export const run = seeds.runner(${list});
`;
}

function writeIfChanged(dir: string, content: string): boolean {
  const target = join(dir, GENERATED_FILE);
  if (existsSync(target) && readFileSync(target, 'utf8') === content) return false;
  mkdirSync(dir, { recursive: true });
  writeFileSync(target, content);
  return true;
}

/**
 * Writes the generated migrations file, and the seeds one when there is a
 * seeds folder. Returns whether either changed.
 */
export function writeGenerated(project: Project): {
  changed: boolean;
  migrations: MigrationFile[];
  /** Null without a seeds folder. */
  seeds: string[] | null;
} {
  const migrations = listMigrations(project.migrationsDir);
  let changed = writeIfChanged(project.migrationsDir, renderGenerated(migrations));
  const seeds = existsSync(project.seedsDir) ? listSeeds(project.seedsDir) : null;
  if (seeds) changed = writeIfChanged(project.seedsDir, renderSeedsGenerated(seeds)) || changed;
  return { changed, migrations, seeds };
}
