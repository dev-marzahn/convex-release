// Generates `<functions>/migrations/_generated.ts` from the numbered migration
// files next to it. The file is committed, like Convex's own `_generated/`.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import type { Project } from './project.ts';

export const GENERATED_FILE = '_generated.ts';

/** `0001_rename_body.ts`: a number, an underscore, a name. */
const MIGRATION_FILE = /^(\d+)_([a-z0-9_]+)\.(ts|js)$/;

export interface MigrationFile {
  /** The number prefix, e.g. 1 for `0001_rename_body.ts`. */
  number: number;
  /** The module name without extension, e.g. `0001_rename_body`. */
  module: string;
  file: string;
}

export class MigrationFileError extends Error {}

/** The numbered migration files, in the order they run. */
export function listMigrations(migrationsDir: string): MigrationFile[] {
  if (!existsSync(migrationsDir)) return [];
  const files: MigrationFile[] = [];
  for (const file of readdirSync(migrationsDir).sort()) {
    if (file.startsWith('_') || file.startsWith('.') || !/\.(ts|js)$/.test(file)) continue;
    if (/\.(test|spec|d)\.(ts|js)$/.test(file)) continue;
    const match = MIGRATION_FILE.exec(file);
    if (!match) {
      throw new MigrationFileError(
        `${file}: migration files are named like 0001_rename_body.ts (a number, an underscore, lowercase letters, digits and underscores).`,
      );
    }
    files.push({ number: Number(match[1]), module: file.replace(/\.(ts|js)$/, ''), file });
  }
  files.sort((a, b) => a.number - b.number);
  for (let i = 1; i < files.length; i++) {
    if (files[i]!.number === files[i - 1]!.number) {
      throw new MigrationFileError(`${files[i - 1]!.file} and ${files[i]!.file} have the same number; each migration needs its own.`);
    }
  }
  return files;
}

export function renderGenerated(migrations: MigrationFile[], packageName = '@dev-marzahn/convex-release'): string {
  const list = migrations.length === 0 ? '[]' : `[\n${migrations.map((m) => `  internal.migrations[${JSON.stringify(m.module)}].default,`).join('\n')}\n]`;
  return `/* eslint-disable */
/**
 * Generated by convex-release from the numbered files in this folder.
 *
 * Don't edit it: \`convex-release new\` and \`convex-release codegen\` rewrite it.
 * @module
 */

import { createRelease } from "${packageName}";
import { components, internal } from "../_generated/api";
import type { DataModel } from "../_generated/dataModel";

const release = createRelease<DataModel>(components.migrations);

/**
 * Defines a data migration. In a numbered file in this folder:
 *
 * \`\`\`ts
 * export default defineMigration({
 *   table: "messages",
 *   migrateOne: (ctx, doc) => { ... },
 * });
 * \`\`\`
 */
export const defineMigration = release.defineMigration;

/** Run by the release image and \`convex-release migrate\`, oldest first. */
export const { start, status } = release.upgrade(${list});
`;
}

/** Writes the generated file. Returns whether its content changed. */
export function writeGenerated(project: Project): {
  changed: boolean;
  migrations: MigrationFile[];
} {
  const migrations = listMigrations(project.migrationsDir);
  const target = join(project.migrationsDir, GENERATED_FILE);
  const content = renderGenerated(migrations);
  const previous = existsSync(target) ? readFileSync(target, 'utf8') : undefined;
  if (previous === content) return { changed: false, migrations };
  mkdirSync(project.migrationsDir, { recursive: true });
  writeFileSync(target, content);
  return { changed: true, migrations };
}
