// `convex-release init --ci`: GitHub Actions workflows for the user's repo.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

import type { PackageManager } from './init.ts';
import type { Project } from './project.ts';

interface Toolchain {
  setup: string;
  install: string;
  /** Runs a package binary, e.g. `bunx convex-release`. */
  exec: string;
}

export function toolchain(pm: PackageManager): Toolchain {
  const node = `      - uses: actions/setup-node@v7
        with:
          node-version: 24`;
  switch (pm) {
    case 'bun':
      return {
        setup: `${node}\n      - uses: oven-sh/setup-bun@v2`,
        install: 'bun install --frozen-lockfile',
        exec: 'bunx',
      };
    case 'pnpm':
      return { setup: `      - uses: pnpm/action-setup@v4\n${node}`, install: 'pnpm install --frozen-lockfile', exec: 'pnpm exec' };
    case 'yarn':
      return { setup: node, install: 'yarn install --immutable', exec: 'yarn' };
    case 'npm':
      return { setup: node, install: 'npm ci', exec: 'npx' };
  }
}

/** The branch pushes deploy from: origin's default branch, else main. */
export function defaultBranch(root: string): string {
  const result = spawnSync('git', ['symbolic-ref', '--short', 'refs/remotes/origin/HEAD'], { cwd: root, encoding: 'utf8' });
  return result.status === 0 ? result.stdout.trim().replace(/^origin\//, '') : 'main';
}

interface Context {
  tools: Toolchain;
  branch: string;
  /** The Convex project's folder relative to the repo root, '' at the root. */
  dir: string;
}

function workingDirectory(ctx: Context): string {
  return ctx.dir ? `\n    defaults:\n      run:\n        working-directory: ${ctx.dir}` : '';
}

export function deployWorkflow(ctx: Context): string {
  return `# Generated by convex-release init --ci. Edit freely.
#
# Pull requests: \`verify\` compares the migrations with the target branch. It
# needs no deployment or secrets, so it runs on pull requests from forks too.
# Pushes to ${ctx.branch}: \`deploy\` pushes the code and runs pending migrations.
#
# Secrets: CONVEX_DEPLOY_KEY for Convex Cloud (Dashboard > Settings > Deploy
# keys). For a self-hosted backend, set CONVEX_SELF_HOSTED_URL and
# CONVEX_SELF_HOSTED_ADMIN_KEY instead.
name: Convex

on:
  pull_request:
  push:
    branches: [${ctx.branch}]

concurrency:
  group: convex-\${{ github.ref }}
  cancel-in-progress: false

permissions:
  contents: read

jobs:
  verify:
    if: github.event_name == 'pull_request'
    runs-on: ubuntu-latest${workingDirectory(ctx)}
    steps:
      - uses: actions/checkout@v7
        with:
          fetch-depth: 0
${ctx.tools.setup}
      - run: ${ctx.tools.install}
      - run: ${ctx.tools.exec} convex-release verify

  deploy:
    if: github.event_name == 'push'
    runs-on: ubuntu-latest
    environment: production${workingDirectory(ctx)}
    steps:
      - uses: actions/checkout@v7
${ctx.tools.setup}
      - run: ${ctx.tools.install}
      - run: ${ctx.tools.exec} convex-release deploy --timeout 1800
        env:
          CONVEX_DEPLOY_KEY: \${{ secrets.CONVEX_DEPLOY_KEY }}
          CONVEX_SELF_HOSTED_URL: \${{ secrets.CONVEX_SELF_HOSTED_URL }}
          CONVEX_SELF_HOSTED_ADMIN_KEY: \${{ secrets.CONVEX_SELF_HOSTED_ADMIN_KEY }}
`;
}

export function imageWorkflow(ctx: Context): string {
  // `run` steps already execute in the project's folder.
  const context = '.';
  return `# Generated by convex-release init --ci. Edit freely.
#
# Tags like v1.4.0 build the release image for amd64 and arm64 and push it to
# ghcr.io/<owner>/<repo>:1.4.0 and :latest. Before pushing, it upgrades the
# previous tag's image to this one in throwaway containers; a failed upgrade
# stops the release.
name: Image

on:
  push:
    tags: ['v*']

permissions:
  contents: read
  packages: write

jobs:
  image:
    runs-on: ubuntu-latest${workingDirectory(ctx)}
    steps:
      - uses: actions/checkout@v7
        with:
          fetch-depth: 0
${ctx.tools.setup}
      - run: ${ctx.tools.install}
      - uses: docker/setup-qemu-action@v4
      - uses: docker/setup-buildx-action@v4
      - uses: docker/login-action@v4
        with:
          registry: ghcr.io
          username: \${{ github.actor }}
          password: \${{ secrets.GITHUB_TOKEN }}
      - name: Names
        id: names
        run: |
          echo "image=ghcr.io/\${GITHUB_REPOSITORY,,}" >> "$GITHUB_OUTPUT"
          echo "version=\${GITHUB_REF_NAME#v}" >> "$GITHUB_OUTPUT"
          previous=$(git describe --tags --abbrev=0 --match 'v*' "\${GITHUB_REF_NAME}^" 2>/dev/null || true)
          echo "previous=\${previous#v}" >> "$GITHUB_OUTPUT"
      - name: Build for the upgrade test
        run: docker buildx build --load -t candidate:test ${context}
      - name: Upgrade from \${{ steps.names.outputs.previous }}
        if: steps.names.outputs.previous != ''
        run: ${ctx.tools.exec} convex-release test-upgrade --from \${{ steps.names.outputs.image }}:\${{ steps.names.outputs.previous }} --to candidate:test
      - name: Build and push
        run: >-
          docker buildx build ${context} --push
          --platform linux/amd64,linux/arm64
          -t \${{ steps.names.outputs.image }}:\${{ steps.names.outputs.version }}
          -t \${{ steps.names.outputs.image }}:latest
`;
}

/** Writes the workflows that don't exist yet; returns their paths relative to the repo. */
export function writeWorkflows(project: Project, pm: PackageManager, withImage: boolean): string[] {
  const top = spawnSync('git', ['rev-parse', '--show-toplevel'], { cwd: project.root, encoding: 'utf8' });
  const repoRoot = top.status === 0 ? top.stdout.trim() : project.root;
  const ctx: Context = { tools: toolchain(pm), branch: defaultBranch(project.root), dir: relative(repoRoot, project.root).split('\\').join('/') };
  const dir = join(repoRoot, '.github/workflows');
  mkdirSync(dir, { recursive: true });
  const files: Record<string, string> = { 'convex.yml': deployWorkflow(ctx) };
  if (withImage) files['image.yml'] = imageWorkflow(ctx);
  const written: string[] = [];
  for (const [name, content] of Object.entries(files)) {
    const path = join(dir, name);
    if (existsSync(path)) continue;
    writeFileSync(path, content);
    written.push(relative(repoRoot, path));
  }
  return written;
}
